    # ============================================================
    # PARÁMETROS DEL FLUIDO (Agua a 20°C, si es otra temperatura,
    # los datos los podemos sacar de las tablas Cengel)
    # ============================================================

    # Propiedades
    rho = 1000.0  # densidad [kg/m³]
    mu = 0.001  # viscosidad dinámica [Pa·s]

    # Diámetros comerciales disponibles en aliexpress
    diametros_mercado = np.array(
        [4, 22, 21, 20, 18, 16, 12, 14, 11, 10, 8, 7, 6, 5]
    )  # en milimetros
    diametros_mercado_m = diametros_mercado / 1000.0  # convertir a metros

    # Caudal y diámetro reales de operación (canal de riego)
    Q_real = 0.001  # 1 L/s
    D_real = 0.5  # diámetro real del canal, 0.5 m

    # Rango de diámetros de columna: ajustado a los diámetros comerciales
    # disponibles (4-22 mm), con un pequeño margen para que todas las
    # líneas de referencia queden dentro del gráfico.
    D_min = diametros_mercado_m.min() * 0.8
    D_max = diametros_mercado_m.max() * 1.15
    num_D = 100

    # Rango de caudal: se extiende hacia valores bajos para poder mostrar
    # dentro de la superficie las fronteras de régimen (Re=2300 y Re=4000)
    # y el Re_real del canal, además de Q_real como línea vertical.
    Q_min = 1e-6
    Q_max = Q_real * 1.5
    num_Q = 200

    Q_rango = np.logspace(np.log10(Q_min), np.log10(Q_max), num_Q)
    D_rango = np.linspace(D_min, D_max, num_D)

    graficar_contorno_reynolds(
        Q_rango,
        D_rango,
        rho,
        mu,
        log_scale=True,
        diametros_mercado=diametros_mercado_m,
        Q_real=Q_real,
        D_real=D_real,
    )
